#!/usr/bin/env python3
# Regenerates .github/workflows/vision-connect.yml from the upstream RustDesk workflow
# (.github/workflows/flutter-build.yml): only the Windows x64 Flutter build, no signing, no MSI,
# plus the Vision Connect branding step. Run from the repository root after merging upstream:
#     python3 vision/make_workflow.py
import io, re, sys

SRC = ".github/workflows/flutter-build.yml"
DST = ".github/workflows/vision-connect.yml"
s = io.open(SRC, encoding="utf-8").read()

# global env block (versions of tools) - keep everything except secrets / inputs
m = re.search(r"^env:\n(.*?)^jobs:\n", s, re.S | re.M)
env = []
for line in m.group(1).splitlines():
    if "secrets." in line or "inputs." in line:
        continue
    env.append(line)
env = "\n".join(env).rstrip()

# the Windows flutter job
j = re.search(r"^  build-for-windows-flutter:\n(.*?)(?=^  [A-Za-z0-9_-]+:\n)", s, re.S | re.M).group(1)
steps_txt = j.split("    steps:\n", 1)[1]
steps = re.split(r"(?m)^(?=      - )", steps_txt)
steps = [x for x in steps if x.strip()]

def name(st):
    m = re.search(r"- name: (.*)", st)
    return m.group(1).strip() if m else st.strip().splitlines()[0]

KEEP = [
    "Export GitHub Actions cache environment variables",
    "Checkout source code",
    "Restore bridge files",
    "Install LLVM and Clang",
    "Install flutter",
    "Replace engine with rustdesk custom flutter engine",
    "Patch flutter",
    "Install Rust toolchain",
    "- uses: Swatinem/rust-cache",
    "Setup vcpkg with Github Actions binary cache",
    "Install vcpkg dependencies",
    "Build rustdesk",
    "find Runner.res",
    "Download RustDeskTempTopMostWindow artifacts",
    "Build self-extracted executable",
]
SUB = {
    "${{ matrix.job.arch == 'aarch64' && 'bridge-artifact-flutter-3.44' || 'bridge-artifact' }}": "bridge-artifact",
    "${{ matrix.job.arch == 'aarch64' && env.FLUTTER_WINDOWS_ARM_VERSION || env.FLUTTER_VERSION }}": "${{ env.FLUTTER_VERSION }}",
    "${{ matrix.job.arch == 'aarch64' && 'topmostwindow-artifacts-ARM64' || 'topmostwindow-artifacts-x64' }}": "topmostwindow-artifacts-x64",
    "${{ matrix.job.target }}": "x86_64-pc-windows-msvc",
    "${{ matrix.job.os }}": "windows-2022",
    "${{ matrix.job.arch }}": "x86_64",
    "${{ matrix.job.flutter-arch }}": "x64",
    "${{ matrix.job.vcpkg-triplet }}": "x64-windows-static",
    "${{ matrix.job.build-args }}": "--vram",
}
BRAND = '''      - name: Apply Vision Connect branding
        shell: bash
        run: python3 vision/brand.py

'''
out = []
for want in KEEP:
    hit = [st for st in steps if name(st).startswith(want.replace("- uses: ", "- uses: ")) or st.lstrip().startswith(want)]
    if len(hit) != 1:
        sys.exit("make_workflow.py: step not found exactly once: %r (%d)" % (want, len(hit)))
    st = hit[0]
    # drop conditions that referred to the matrix / inputs (we always build x64 and always package)
    st = re.sub(r"(?m)^        if: .*\n", "", st)
    for a, b in SUB.items():
        st = st.replace(a, b)
    if "matrix." in st or "inputs." in st or "secrets." in st:
        sys.exit("make_workflow.py: unresolved expression in step %r" % want)
    if want == "Build self-extracted executable":
        st = st.replace("./SignOutput/rustdesk-${{ env.VERSION }}-x86_64.exe", "./SignOutput/VisionConnect-${{ env.VERSION }}-x86_64.exe")
        if "VisionConnect-" not in st:
            sys.exit("make_workflow.py: output name not patched")
    out.append(st if st.endswith("\n\n") else st.rstrip("\n") + "\n\n")
    if want == "Restore bridge files":
        out.append(BRAND)

head = '''# GENERATED by vision/make_workflow.py from flutter-build.yml - do not edit by hand.
# Vision Connect (Vision IT Serwis) - Windows x64 build of the RustDesk sources with vision/brand.py applied.
name: Vision Connect - Windows

on:
  workflow_dispatch:

env:
%s
  UPLOAD_ARTIFACT: "true"

jobs:
  generate-bridge:
    uses: ./.github/workflows/bridge.yml

  build-RustDeskTempTopMostWindow:
    uses: ./.github/workflows/third-party-RustDeskTempTopMostWindow.yml
    with:
      upload-artifact: true
      target: windows-2022
      configuration: Release
      platform: x64
      target_version: Windows10

  build-vision-connect:
    name: Vision Connect x86_64-pc-windows-msvc
    needs: [build-RustDeskTempTopMostWindow, generate-bridge]
    runs-on: windows-2022
    steps:
''' % env
tail = '''      - name: Upload Vision Connect (single exe)
        uses: actions/upload-artifact@043fb46d1a93c77aae656e7c1c64a875d1fc6a0a # v7.0.1
        with:
          name: VisionConnect-windows-x86_64
          path: SignOutput
          if-no-files-found: error

      - name: Upload Vision Connect (unpacked folder)
        uses: actions/upload-artifact@043fb46d1a93c77aae656e7c1c64a875d1fc6a0a # v7.0.1
        with:
          name: VisionConnect-windows-x86_64-folder
          path: rustdesk
'''
io.open(DST, "w", encoding="utf-8", newline="\n").write(head + "".join(out) + tail)
print("written", DST)
